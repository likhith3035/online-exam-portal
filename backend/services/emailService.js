const nodemailer = require('nodemailer');

let transporter = null;

function getTransporter() {
  if (transporter) return transporter;

  const host = process.env.SMTP_HOST || 'smtp.gmail.com';
  const port = Number(process.env.SMTP_PORT) || 587;
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;

  if (user && pass) {
    transporter = nodemailer.createTransporter({
      host,
      port,
      secure: port === 465,
      auth: { user, pass }
    });
  }
  return transporter;
}

/**
 * Sends a stylized HTML scorecard email to the student
 */
async function sendResultEmail({ student, exam, summary }) {
  if (!student || !student.email) {
    console.log('Skipping email: Student email not found');
    return { success: false, reason: 'No student email' };
  }

  const mailTransporter = getTransporter();

  const isPass = summary.result === 'PASS';
  const statusColor = isPass ? '#16a34a' : '#dc2626';
  const statusBadge = isPass ? 'PASSED ✓' : 'FAILED ✗';

  const htmlContent = `
    <!DOCTYPE html>
    <html>
    <head>
      <meta charset="utf-8">
      <style>
        body { font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; background-color: #f1f5f9; margin: 0; padding: 20px; color: #1e293b; }
        .card { max-width: 600px; margin: 0 auto; background: #ffffff; border-radius: 12px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.08); }
        .header { background: linear-gradient(135deg, #1e3a8a 0%, #0f172a 100%); color: #ffffff; padding: 30px 24px; text-align: center; }
        .header h1 { margin: 0; font-size: 24px; letter-spacing: 0.5px; }
        .header p { margin: 6px 0 0 0; color: #93c5fd; font-size: 14px; }
        .content { padding: 28px 24px; }
        .badge { display: inline-block; padding: 6px 18px; border-radius: 20px; font-weight: bold; font-size: 16px; color: #fff; background-color: ${statusColor}; margin: 15px 0; }
        .metrics-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 14px; margin: 20px 0; }
        .metric-box { background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px; padding: 12px 16px; text-align: center; }
        .metric-val { font-size: 20px; font-weight: bold; color: #1e3a8a; margin-top: 4px; }
        .metric-lbl { font-size: 12px; color: #64748b; text-transform: uppercase; font-weight: 600; }
        .table-info { width: 100%; border-collapse: collapse; margin-top: 15px; }
        .table-info td { padding: 10px 12px; border-bottom: 1px solid #e2e8f0; font-size: 14px; }
        .table-info td:first-child { color: #64748b; font-weight: 500; }
        .footer { background: #f8fafc; padding: 18px; text-align: center; font-size: 12px; color: #94a3b8; border-top: 1px solid #e2e8f0; }
      </style>
    </head>
    <body>
      <div class="card">
        <div class="header">
          <h1>NBKRIST Examination Cell</h1>
          <p>Official Online Examination Performance Report</p>
        </div>
        <div class="content">
          <p>Dear <strong>${student.name}</strong> (${student.studentId}),</p>
          <p>Your examination results for <strong>${exam.examName}</strong> have been evaluated and recorded.</p>
          
          <div style="text-align: center;">
            <div class="badge">${statusBadge}</div>
          </div>

          <div class="metrics-grid">
            <div class="metric-box">
              <div class="metric-lbl">Marks Obtained</div>
              <div class="metric-val">${summary.obtainedMarks} / ${summary.totalMarks}</div>
            </div>
            <div class="metric-box">
              <div class="metric-lbl">Percentage</div>
              <div class="metric-val">${summary.percentage}%</div>
            </div>
          </div>

          <table class="table-info">
            <tr><td>Total Questions</td><td><strong>${summary.totalQuestions}</strong></td></tr>
            <tr><td>Correct Answers</td><td><strong style="color: #16a34a;">${summary.correctCount}</strong></td></tr>
            <tr><td>Wrong Answers</td><td><strong style="color: #dc2626;">${summary.wrongCount}</strong></td></tr>
            <tr><td>Unanswered</td><td><strong>${summary.unansweredCount}</strong></td></tr>
            <tr><td>Passing Mark</td><td>${summary.passMarks}</td></tr>
            <tr><td>Time Taken</td><td>${summary.timeTaken}</td></tr>
            <tr><td>Examination Date</td><td>${new Date().toLocaleDateString('en-IN')}</td></tr>
          </table>

          <p style="margin-top: 24px; font-size: 13px; color: #64748b;">
            This is an automated performance report generated by the NBKRIST Online Exam Portal. The official marks have been registered in the controller's grade records.
          </p>
        </div>
        <div class="footer">
          &copy; ${new Date().getFullYear()} N.B.K.R. Institute of Science & Technology, Vidyanagar, Andhra Pradesh.
        </div>
      </div>
    </body>
    </html>
  `;

  if (!mailTransporter) {
    console.log(`[Email Simulation] Result notification prepared for ${student.name} <${student.email}> | Exam: ${exam.examName} | Score: ${summary.obtainedMarks}/${summary.totalMarks} (${summary.result})`);
    console.log(`[Email Notice] To send live emails, configure SMTP_USER and SMTP_PASS in .env`);
    return { success: true, simulated: true };
  }

  try {
    const info = await mailTransporter.sendMail({
      from: process.env.SMTP_FROM || '"NBKRIST Exam Cell" <noreply@nbkrist.ac.in>',
      to: student.email,
      subject: `[NBKRIST Exam Result] ${exam.examName} - ${statusBadge}`,
      html: htmlContent
    });
    console.log(`[Email Sent] Message sent to ${student.email}: ${info.messageId}`);
    return { success: true, messageId: info.messageId };
  } catch (error) {
    console.error(`[Email Error] Failed to send email to ${student.email}:`, error.message);
    return { success: false, error: error.message };
  }
}

module.exports = {
  sendResultEmail
};
